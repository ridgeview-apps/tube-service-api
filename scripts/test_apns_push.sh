#!/usr/bin/env bash
# Queue and monitor a controlled APNs test push through the deployed Tube
# Service API.
#
# Prerequisites:
#   * APNS_TEST_PUSH_ENABLED=true on the API service.
#   * APNs credentials on the notification worker only.
#   * A registered iOS device ID.
#   * curl.
#
# Usage:
#   scripts/test_apns_push.sh https://your-api-domain
#
# Set TUBE_API_KEY and TUBE_DEVICE_ID to avoid prompts. A local wrapper file is
# ignored by Git; see scripts/test_apns_push.local.example.sh.

set -euo pipefail

usage() {
  printf 'Usage: %s https://your-api-domain\n' "${0##*/}" >&2
  exit 2
}

api_base="${1:-${TUBE_API_URL:-}}"
[[ -n "$api_base" ]] || usage
api_base="${api_base%/}"

api_key="${TUBE_API_KEY:-}"
device_id="${TUBE_DEVICE_ID:-}"

if [[ -z "$api_key" ]]; then
  read -r -s -p 'API key: ' api_key
  printf '\n'
fi

if [[ -z "$device_id" ]]; then
  read -r -p 'Registered iOS device ID: ' device_id
fi

[[ -n "$api_key" ]] || { printf 'An API key is required.\n' >&2; exit 2; }
[[ -n "$device_id" ]] || { printf 'A device ID is required.\n' >&2; exit 2; }

# Device IDs generated by this app are identifiers and should be safe in a URL
# path. Reject characters that would change the path rather than guessing how
# the server expects them to be encoded.
[[ "$device_id" =~ ^[A-Za-z0-9._~-]+$ ]] || {
  printf 'The device ID contains unsupported URL-path characters.\n' >&2
  exit 2
}

tmp_dir="$(mktemp -d "${TMPDIR:-/tmp}/tube-apns-test.XXXXXX")"
trap 'rm -rf "$tmp_dir"' EXIT
config_file="$tmp_dir/curl.conf"
body_file="$tmp_dir/response.json"

# Keep the sensitive header out of the command line and shell history.
umask 077
printf 'header = "X-API-Key: %s"\n' "$api_key" > "$config_file"
unset api_key

request() {
  local method="$1"
  local url="$2"
  status_code="$(curl \
    --silent \
    --show-error \
    --output "$body_file" \
    --write-out '%{http_code}' \
    --request "$method" \
    --config "$config_file" \
    "$url")"
}

print_response() {
  printf 'HTTP %s\n' "$status_code"
  if command -v jq >/dev/null 2>&1; then
    jq . "$body_file" || cat "$body_file"
  else
    cat "$body_file"
    printf '\n'
  fi
}

json_value() {
  local field="$1"
  if command -v jq >/dev/null 2>&1; then
    jq -r ".${field} // empty" "$body_file"
  else
    sed -nE "s/.*\\\"${field}\\\"[[:space:]]*:[[:space:]]*\\\"?([^,}\\\"]+).*/\\1/p" "$body_file"
  fi
}

test_url="${api_base}/v1/notification-devices/${device_id}/test-push"
request POST "$test_url"
print_response

if [[ "$status_code" != "202" ]]; then
  printf 'Test push was not queued. Do not revoke the old APNs key.\n' >&2
  exit 1
fi

delivery_id="$(json_value delivery_id)"
[[ "$delivery_id" =~ ^[0-9]+$ ]] || {
  printf 'The API response did not include a valid delivery ID.\n' >&2
  exit 1
}

timeout_seconds="${TUBE_TEST_TIMEOUT_SECONDS:-90}"
poll_seconds="${TUBE_TEST_POLL_SECONDS:-3}"
[[ "$timeout_seconds" =~ ^[1-9][0-9]*$ && "$poll_seconds" =~ ^[1-9][0-9]*$ ]] || {
  printf 'Polling timeout and interval must be positive integers.\n' >&2
  exit 2
}
deadline=$((SECONDS + timeout_seconds))
status_url="${test_url}/${delivery_id}"

while (( SECONDS < deadline )); do
  sleep "$poll_seconds"
  request GET "$status_url"
  print_response

  if [[ "$status_code" != "200" ]]; then
    printf 'Could not read test-push status. Do not revoke the old APNs key.\n' >&2
    exit 1
  fi

  delivery_status="$(json_value status)"
  case "$delivery_status" in
    sent)
      printf 'APNs accepted the test push. Confirm it arrived on the device before revoking the old key.\n'
      exit 0
      ;;
    failed | skipped)
      printf 'The worker did not send the test push. Do not revoke the old APNs key.\n' >&2
      exit 1
      ;;
    pending)
      ;;
    *)
      printf 'The API returned an unknown test-push status.\n' >&2
      exit 1
      ;;
  esac
done

printf 'Timed out waiting for the notification worker. Do not revoke the old APNs key.\n' >&2
exit 1
